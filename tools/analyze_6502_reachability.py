#!/usr/bin/env python3
"""Conservative 6502 reachability analyzer for the canonical 32 KiB NROM PRG."""
from pathlib import Path
import argparse, json, struct

# Official NMOS 6502 opcodes: opcode -> (mnemonic, length, flow)
# flow: next, branch, jsr, jmp, stop, ind
T={}
def add(ops,m,l,f="next"):
    for o in ops:T[o]=(m,l,f)
# lengths/flow are sufficient for safe reachability; mnemonic is diagnostic.
for o in [0x00,0x40,0x60]: add([o],{0x00:("BRK",1,"stop"),0x40:("RTI",1,"stop"),0x60:("RTS",1,"stop")}[o][0],1,"stop")
add([0x20],"JSR",3,"jsr"); add([0x4C],"JMP",3,"jmp"); add([0x6C],"JMP",3,"ind")
add([0x10,0x30,0x50,0x70,0x90,0xB0,0xD0,0xF0],"BR",2,"branch")
# official opcode lengths grouped
L1=[0x08,0x0A,0x18,0x28,0x2A,0x38,0x48,0x4A,0x58,0x68,0x6A,0x78,0x88,0x8A,0x98,0x9A,0xA8,0xAA,0xB8,0xBA,0xC8,0xCA,0xD8,0xE8,0xEA,0xF8]
L2=[0x01,0x05,0x06,0x09,0x11,0x15,0x16,0x21,0x24,0x25,0x26,0x29,0x31,0x35,0x36,0x41,0x45,0x46,0x49,0x51,0x55,0x56,0x61,0x65,0x66,0x69,0x71,0x75,0x76,0x81,0x84,0x85,0x86,0x91,0x94,0x95,0x96,0xA0,0xA1,0xA2,0xA4,0xA5,0xA6,0xA9,0xB1,0xB4,0xB5,0xB6,0xC0,0xC1,0xC4,0xC5,0xC6,0xC9,0xD1,0xD5,0xD6,0xE0,0xE1,0xE4,0xE5,0xE6,0xE9,0xF1,0xF5,0xF6]
L3=[0x0D,0x0E,0x19,0x1D,0x1E,0x2C,0x2D,0x2E,0x39,0x3D,0x3E,0x4D,0x4E,0x59,0x5D,0x5E,0x6D,0x6E,0x79,0x7D,0x7E,0x8C,0x8D,0x8E,0x99,0x9D,0xAC,0xAD,0xAE,0xB9,0xBC,0xBD,0xBE,0xCC,0xCD,0xCE,0xD9,0xDD,0xDE,0xEC,0xED,0xEE,0xF9,0xFD,0xFE]
for o in L1:T.setdefault(o,("OP",1,"next"))
for o in L2:T.setdefault(o,("OP",2,"next"))
for o in L3:T.setdefault(o,("OP",3,"next"))

def idx(a): return a-0x8000 if 0x8000<=a<=0xFFFF else None
def main():
 ap=argparse.ArgumentParser();ap.add_argument("prg",type=Path);ap.add_argument("--out",type=Path,default=Path("build/rom/reachability.json"));a=ap.parse_args()
 p=a.prg.read_bytes()
 if len(p)!=32768:raise SystemExit("expected 32768-byte NROM-256 PRG")
 nmi,reset,irq=struct.unpack("<HHH",p[-6:]); roots=[reset,nmi,irq]
 q=list(roots); seen=set(); ins={}; bad=[]
 while q:
  pc=q.pop()
  while pc not in seen:
   i=idx(pc)
   if i is None: break
   op=p[i]
   if op not in T: bad.append({"pc":f"0x{pc:04X}","opcode":f"0x{op:02X}"});break
   m,l,f=T[op]
   if i+l>len(p):break
   seen.add(pc); raw=p[i:i+l]; ins[pc]={"opcode":op,"len":l,"flow":f,"bytes":raw.hex()}
   nxt=(pc+l)&0xffff
   if f=="branch":
    rel=raw[1]-256 if raw[1]&0x80 else raw[1];q.append((nxt+rel)&0xffff);pc=nxt;continue
   if f in ("jsr","jmp"):
    target=raw[1]|(raw[2]<<8);q.append(target)
    if f=="jmp":break
    pc=nxt;continue
   if f in ("stop","ind"):break
   pc=nxt
 codebytes=sum(v["len"] for v in ins.values())
 out={"roots":[f"0x{x:04X}" for x in roots],"instructions":len(ins),"reachable_code_bytes":codebytes,
      "prg_bytes":len(p),"coverage_percent":round(codebytes*100/len(p),3),"unknown_opcode_stops":bad[:100]}
 a.out.parent.mkdir(parents=True,exist_ok=True);a.out.write_text(json.dumps(out,indent=2)+"\n");print(json.dumps(out,indent=2))
if __name__=="__main__":main()
